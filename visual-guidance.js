export function buildVisualGuidance(mode = 'static') {
    if (mode === 'off') return `采用简洁文字排版：清楚的篇名和完整正文，常规单列阅读，正文至少 17px，手机不缩小，不添加装饰性组件。\n\n${OUTPUT_CONTRACT.trim()}`;
    return [
        EDITORIAL_GUIDANCE.trim(),
        mode === 'dynamic'
            ? '本次为动态排版：只用少量 CSS 入场或装饰动画，正文始终可见；prefers-reduced-motion 下关闭动画，不闪烁、不自动滚动。'
            : '本次为静态排版：不使用动画，以字号、留白和构图形成层次。',
        OUTPUT_CONTRACT.trim(),
        '最终交付门槛：基础 CSS 就是紧凑手机版，桌面增强使用 min-width；390px 手机第一句剧情距文档顶部约 160px 以内，篇头装饰不参与高度计算，引子也至少 17px。其余检查：本篇母题已落实为构图与叙事细节，人物身份明确，规定的内容、数值和结局完整，全文可滚动到达。仅提交符合这些条件的 HTML 作品。',
    ].filter(Boolean).join('\n\n');
}
